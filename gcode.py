"""Revisión de gcode para la K2: qué impresora, qué filamentos, hasta dónde se mueve.

Es la red de seguridad del plugin. Creality Print a veces se cambia solo al perfil
K2 Pro (cama de 300 mm) y un 3MF descargado trae el perfil de otra máquina (K1C…);
en los dos casos el gcode sale "bien" y la impresora lo acepta, pero el cabezal
acaba golpeando el lateral. Por eso aquí se miden los movimientos reales, no solo
lo que dice la cabecera.
"""
from __future__ import annotations

import base64
import os
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

# Margen para no marcar como fuera de cama un redondeo del laminador.
TOLERANCIA_MM = 0.5

_RE_COMENTARIO = re.compile(r"^;\s*([A-Za-z0-9_ ()\[\]]+?)\s*[=:]\s*(.*)$")
_RE_EJE = re.compile(r"([XYZ])(-?\d*\.?\d+)")
_RE_HERRAMIENTA = re.compile(r"^T(\d+)\s*(?:;.*)?$")
_RE_MINIATURA = re.compile(r"^; thumbnail begin (\d+x\d+)")


@dataclass
class Caja:
    """Caja envolvente de un conjunto de movimientos."""

    x_min: float = float("inf")
    x_max: float = float("-inf")
    y_min: float = float("inf")
    y_max: float = float("-inf")
    z_max: float = float("-inf")

    def incluir(self, x: float, y: float, z: float) -> None:
        self.x_min = min(self.x_min, x)
        self.x_max = max(self.x_max, x)
        self.y_min = min(self.y_min, y)
        self.y_max = max(self.y_max, y)
        self.z_max = max(self.z_max, z)

    @property
    def vacia(self) -> bool:
        return self.x_min == float("inf")

    def como_dict(self) -> dict | None:
        if self.vacia:
            return None
        return {
            "x": [round(self.x_min, 2), round(self.x_max, 2)],
            "y": [round(self.y_min, 2), round(self.y_max, 2)],
            "z_max": round(self.z_max, 2),
        }


@dataclass
class Informe:
    ruta: str
    ajustes: dict[str, str] = field(default_factory=dict)
    herramientas: list[int] = field(default_factory=list)
    miniaturas: list[str] = field(default_factory=list)
    start_print: str | None = None
    carga_malla: bool = False
    # Movimientos de las capas, sin los bloques de la máquina (purga, cambio de color).
    pieza: Caja = field(default_factory=Caja)
    # Todo lo que se mueve, incluida la purga y la rampa de desecho (Y 291,5 en la K2).
    desplazamientos: Caja = field(default_factory=Caja)
    cama: tuple[float, float, float, float] | None = None
    altura_maxima: float | None = None
    problemas: list[str] = field(default_factory=list)
    avisos: list[str] = field(default_factory=list)

    @property
    def apto(self) -> bool:
        return not self.problemas

    def valor(self, clave: str) -> str | None:
        return self.ajustes.get(clave)

    def lista(self, clave: str) -> list[str]:
        return partir_lista(self.ajustes.get(clave, ""))

    @property
    def generado_por(self) -> str:
        return self.ajustes.get("generated by", "")

    @property
    def modelo_impresora(self) -> str:
        return self.ajustes.get("printer_model", "")

    @property
    def tiempo_estimado(self) -> str:
        return self.ajustes.get("estimated printing time (normal mode)", "")

    def resumen(self) -> dict:
        tipos = self.lista("filament_type")
        colores = self.lista("filament_colour")
        filamentos = []
        for t in self.herramientas:
            filamentos.append({
                "extrusor": t + 1,
                "gcode": f"T{t}",
                "tipo": tipos[t] if t < len(tipos) else None,
                "color": colores[t] if t < len(colores) else None,
                "perfil": _en(self.lista("filament_settings_id"), t),
            })
        return {
            "archivo": self.ruta,
            "apto": self.apto,
            "problemas": self.problemas,
            "avisos": self.avisos,
            "laminador": self.generado_por,
            "impresora": self.modelo_impresora,
            "perfil_maquina": self.valor("printer_settings_id"),
            "perfil_proceso": self.valor("print_settings_id"),
            "filamentos": filamentos,
            "tiempo_estimado": self.tiempo_estimado,
            "filamento_g": self.valor("total filament weight [g]") or self.valor("filament used [g]"),
            "filamento_m": _metros(self.valor("filament used [mm]")),
            "capas": self.valor("total layer number") or self.valor("total layers count"),
            "cama_mm": list(self.cama) if self.cama else None,
            "altura_maxima_mm": self.altura_maxima,
            "caja_pieza": self.pieza.como_dict(),
            "caja_movimientos": self.desplazamientos.como_dict(),
            "miniaturas": self.miniaturas,
            "start_print": self.start_print,
        }


def _metros(mm: str | None) -> str | None:
    """'571.95' o '571.95, 0.00' (uno por filamento) -> '0.57'."""
    if not mm:
        return None
    try:
        return f"{sum(float(v) for v in mm.split(',')) / 1000:.2f}"
    except ValueError:
        return None


def _en(lista: list[str], i: int) -> str | None:
    return lista[i] if i < len(lista) else None


def partir_lista(valor: str) -> list[str]:
    """`"A";"B"` o `#FFF;#000` -> ['A', 'B'] / ['#FFF', '#000']."""
    if not valor:
        return []
    partes = re.findall(r'"([^"]*)"|([^;]+)', valor)
    return [(a or b).strip() for a, b in partes if (a or b).strip()]


def _cama(ajustes: dict[str, str]) -> tuple[float, float, float, float] | None:
    area = ajustes.get("printable_area")
    if not area:
        return None
    try:
        puntos = [tuple(float(v) for v in p.split("x")) for p in area.split(",")]
    except ValueError:
        return None
    xs = [p[0] for p in puntos]
    ys = [p[1] for p in puntos]
    return (min(xs), max(xs), min(ys), max(ys))


def analizar(
    ruta: str | os.PathLike,
    modelo_esperado: str | None = None,
    cama: tuple[float, float, float] | None = None,
) -> Informe:
    """Lee el gcode entero y devuelve qué hace y si es seguro para la impresora.

    `modelo_esperado` es el `printer_model` que debe tener (p. ej. "Creality K2");
    si no coincide, es un problema, no un aviso.

    `cama` es (ancho, fondo, alto) de la impresora REAL. Hay que pasarla siempre que
    se sepa: un gcode laminado para la K2 Pro dice que su cama mide 300 y, comparado
    consigo mismo, parece correcto.
    """
    ruta = Path(ruta)
    inf = Informe(ruta=str(ruta))
    x = y = z = 0.0
    relativo = False
    herramientas: set[int] = set()
    en_capas = False  # hasta el primer ;LAYER_CHANGE todo es arranque de la máquina
    bloque_maquina = False  # dentro de un ;TYPE:Custom (cambio de filamento, final)

    with open(ruta, "r", encoding="utf-8", errors="replace") as f:
        for linea in f:
            c = linea[:1]
            if c == ";":
                if linea.startswith(";LAYER_CHANGE"):
                    en_capas = True
                    continue
                if linea.startswith(";TYPE:"):
                    bloque_maquina = linea.startswith(";TYPE:Custom")
                    continue
                if linea.startswith("; generated by "):
                    inf.ajustes["generated by"] = linea[15:].strip()
                    continue
                m = _RE_COMENTARIO.match(linea.rstrip())
                if m:
                    inf.ajustes[m.group(1).strip()] = m.group(2).strip()
                elif linea.startswith("; thumbnail begin"):
                    mm = _RE_MINIATURA.match(linea)
                    if mm:
                        inf.miniaturas.append(mm.group(1))
                continue
            if c == "G":
                cmd = linea.split(";", 1)[0].split()
                if not cmd:
                    continue
                g = cmd[0]
                if g in ("G0", "G1", "G2", "G3"):
                    nx, ny, nz = x, y, z
                    for tok in cmd[1:]:
                        eje = tok[:1]
                        try:
                            v = float(tok[1:])
                        except ValueError:
                            continue
                        if eje == "X":
                            nx = x + v if relativo else v
                        elif eje == "Y":
                            ny = y + v if relativo else v
                        elif eje == "Z":
                            nz = z + v if relativo else v
                    x, y, z = nx, ny, nz
                    inf.desplazamientos.incluir(x, y, z)
                    if en_capas and not bloque_maquina:
                        inf.pieza.incluir(x, y, z)
                elif g == "G90":
                    relativo = False
                elif g == "G91":
                    relativo = True
                elif g == "G92":
                    pass
                continue
            if c == "T":
                m = _RE_HERRAMIENTA.match(linea.strip())
                if m:
                    herramientas.add(int(m.group(1)))
                continue
            if c == "M":
                continue
            if linea.startswith("START_PRINT"):
                inf.start_print = inf.start_print or linea.strip()
            elif linea.startswith("BED_MESH_PROFILE LOAD"):
                inf.carga_malla = True

    inf.herramientas = sorted(herramientas) or [0]
    if cama:
        inf.cama = (0.0, float(cama[0]), 0.0, float(cama[1]))
        inf.altura_maxima = float(cama[2])
    else:
        inf.cama = _cama(inf.ajustes)
        try:
            inf.altura_maxima = float(inf.ajustes.get("printable_height", ""))
        except ValueError:
            inf.altura_maxima = None
    _evaluar(inf, modelo_esperado)
    return inf


def _evaluar(inf: Informe, modelo_esperado: str | None) -> None:
    modelo = inf.modelo_impresora
    if modelo_esperado and modelo != modelo_esperado:
        inf.problemas.append(
            f"El gcode es para «{modelo or 'desconocida'}» y la impresora es «{modelo_esperado}». "
            "Relamina con el perfil correcto."
        )
    if inf.cama is None:
        inf.avisos.append("El gcode no dice el tamaño de cama (printable_area); no se han podido comprobar los límites.")
    else:
        x0, x1, y0, y1 = inf.cama
        caja = inf.pieza
        if caja.vacia:
            inf.avisos.append("No hay marcas ;LAYER_CHANGE: no se ha podido separar la pieza del arranque.")
        else:
            fuera = []
            if caja.x_min < x0 - TOLERANCIA_MM or caja.x_max > x1 + TOLERANCIA_MM:
                fuera.append(f"X de {caja.x_min:.1f} a {caja.x_max:.1f} (cama {x0:g}-{x1:g})")
            if caja.y_min < y0 - TOLERANCIA_MM or caja.y_max > y1 + TOLERANCIA_MM:
                fuera.append(f"Y de {caja.y_min:.1f} a {caja.y_max:.1f} (cama {y0:g}-{y1:g})")
            if fuera:
                inf.problemas.append("El cabezal sale de la cama: " + "; ".join(fuera) + ".")
            if inf.altura_maxima and caja.z_max > inf.altura_maxima + TOLERANCIA_MM:
                inf.problemas.append(
                    f"La pieza llega a Z {caja.z_max:.1f} y la máquina solo tiene {inf.altura_maxima:g} mm."
                )
    if "Creality_Print" not in inf.generado_por and "Creality Print" not in inf.generado_por:
        inf.avisos.append(f"No lo ha generado Creality Print ({inf.generado_por or 'desconocido'}).")
        if inf.start_print and not inf.carga_malla:
            inf.avisos.append(
                "Arranque sin BED_MESH_PROFILE LOAD=default: con gcode de Orca la K2 imprime sin malla."
            )
    if not inf.start_print:
        inf.avisos.append("No hay START_PRINT: no calentará ni nivelará como espera la K2.")
    if not inf.miniaturas:
        inf.avisos.append("Sin miniaturas: la pantalla de la impresora no enseñará la vista previa.")


# ---------------------------------------------------------------- miniaturas

def bloque_miniatura(png: bytes, ancho: int, alto: int) -> str:
    """Bloque de miniatura con el mismo formato que escribe Creality Print."""
    b64 = base64.b64encode(png).decode("ascii")
    lineas = [b64[i:i + 78] for i in range(0, len(b64), 78)]
    cuerpo = "\n".join(f"; {l}" for l in lineas)
    return (
        "; THUMBNAIL_BLOCK_START\n\n;\n"
        f"; thumbnail begin {ancho}x{alto} {len(b64)}\n"
        f"{cuerpo}\n"
        "; thumbnail end\n"
        "; THUMBNAIL_BLOCK_END\n\n"
    )


def insertar_miniaturas(ruta: str | os.PathLike, pngs: list[tuple[int, int, bytes]]) -> None:
    """Mete las miniaturas en la cabecera, donde las pone Creality Print.

    Van justo después de `; multicolor_method` (o de HEADER_BLOCK_END si no está).
    Si el gcode ya tiene miniaturas no hace nada.
    """
    ruta = Path(ruta)
    bloques = "".join(bloque_miniatura(png, w, h) for w, h, png in pngs)
    with open(ruta, "r", encoding="utf-8", errors="replace", newline="") as f:
        cabecera = [f.readline() for _ in range(60)]
        if any(l.startswith("; thumbnail begin") for l in cabecera):
            return
        punto = None
        for i, l in enumerate(cabecera):
            if l.startswith("; multicolor_method"):
                punto = i + 1
                break
        if punto is None:
            for i, l in enumerate(cabecera):
                if l.startswith("; HEADER_BLOCK_END"):
                    punto = i + 1
                    break
        if punto is None:
            punto = 0
        fd, tmp = tempfile.mkstemp(suffix=".gcode", dir=ruta.parent)
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as out:
            out.writelines(cabecera[:punto])
            out.write(bloques)
            out.writelines(cabecera[punto:])
            while True:
                trozo = f.read(1 << 20)
                if not trozo:
                    break
                out.write(trozo)
    os.replace(tmp, ruta)
